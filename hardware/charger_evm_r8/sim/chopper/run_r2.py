def evaluate(r102, r103, r104):
    b, typ, _ = bands(r102, r103, r104, leak=True)
    b0, _, _ = bands(r102, r103, r104, leak=False)
    gain = (r102 + r103 + r104) / r104
    return dict(R102=r102, R103=r103, R104=r104, gain_ovp=round(gain, 4),
                ovp_rise_typ=round(typ["OVP_rise"], 3),
                ovp_rise_min_noleak=round(b0["OVP_rise"][0], 3), ovp_rise_max_noleak=round(b0["OVP_rise"][1], 3),
                ovp_rise_min=round(b["OVP_rise"][0], 3), ovp_rise_max=round(b["OVP_rise"][1], 3),
                ovp_fall_min=round(b["OVP_fall"][0], 3), ovp_fall_max=round(b["OVP_fall"][1], 3),
                uvlo_rise_typ=round(typ["UVLO_rise"], 3),
                uvlo_rise_min=round(b["UVLO_rise"][0], 3), uvlo_rise_max=round(b["UVLO_rise"][1], 3),
                uvlo_fall_min=round(b["UVLO_fall"][0], 3), uvlo_fall_max=round(b["UVLO_fall"][1], 3),
                ovp_pin_at_75V=round(75.0 / gain, 3), ovp_pin_at_80V=round(80.0 / gain, 3),
                string_kohm=round((r102 + r103 + r104) / 1e3, 2),
                i_string_uA_at_25V=round(25.0 / (r102 + r103 + r104) * 1e6, 2))


def part2(target):
    """Divider candidates whose leak-corner OVP rising minimum clears the target."""
    say(f"=== Part 2: lever (a) divider candidates, leak-corner OVP rising minimum >= {target:.3f} V ===")
    # Gain needed with the fitted Thevenin resistance (scaling estimate, as the reviewer used): no-leak min target
    fit = evaluate(R102_FIT, R103_FIT, R104_FIT)
    scale_needed = target / fit["ovp_rise_min"]
    say(f"  gain scaling estimate: no-leak minimum {fit['ovp_rise_min_noleak'] * scale_needed:.3f} V, leak-corner "
        f"maximum {fit['ovp_rise_max'] * scale_needed:.3f} V")
    rows = []
    for tag, series in (("E96", eseries(96)), ("E192", eseries(192))):
        r103s = decade_values(series, 40e3, 100e3)
        r104s = decade_values(series, 30e3, 60e3)
        found = []
        for r103, r104 in itertools.product(r103s, r104s):
            e = evaluate(R102_FIT, r103, r104)
            if e["ovp_rise_min"] >= target:
                found.append(e)
        # class "uvlo-kept": the UVLO rising typical stays within 0.05 V of the fitted 9.859 V (R103 + R104 about
        # 116 kOhm), ranked by the OVP rising maximum; class "free": the lowest OVP rising maximum at any UVLO.
        kept = sorted([e for e in found if abs(e["uvlo_rise_typ"] - fit["uvlo_rise_typ"]) <= 0.05],
                      key=lambda e: (e["ovp_rise_max"], abs(e["uvlo_rise_typ"] - fit["uvlo_rise_typ"])))[:3]
        free = sorted(found, key=lambda e: e["ovp_rise_max"])[:1]
        for cls, e in [("uvlo-kept", x) for x in kept] + [("free", x) for x in free]:
            e = dict(series=tag, cls=cls, **e)
            rows.append(e)
            say(f"  {tag} {cls}: R102 845k R103 {e['R103'] / 1e3:g}k R104 {e['R104'] / 1e3:g}k -> OVP rise "
                f"{e['ovp_rise_min']:.3f}-{e['ovp_rise_max']:.3f} V (no leak {e['ovp_rise_min_noleak']:.3f}-"
                f"{e['ovp_rise_max_noleak']:.3f}, typ {e['ovp_rise_typ']:.3f}); fall {e['ovp_fall_min']:.3f}-"
                f"{e['ovp_fall_max']:.3f}; UVLO rise {e['uvlo_rise_min']:.3f}-{e['uvlo_rise_max']:.3f} V")
    return rows, fit


def part3(target):
    """Lower string impedance: the whole string scaled by k (E192 values), and the lowest leak-corner maximum."""
    say(f"=== Part 3: string impedance against the leak-corner maximum (minimum >= {target:.3f} V) ===")
    series = eseries(192)
    rows = []
    for k in (1.0, 0.75, 0.5, 0.25, 0.1):
        r102s = [x for x in decade_values(series, 845e3 * k * 0.97, 845e3 * k * 1.03)]
        best = None
        for r102 in r102s:
            for r103 in decade_values(series, 64.9e3 * k * 0.85, 64.9e3 * k * 1.2):
                for r104 in decade_values(series, 51.1e3 * k * 0.85, 51.1e3 * k * 1.1):
                    e = evaluate(r102, r103, r104)
                    if e["ovp_rise_min"] < target:
                        continue
                    if abs(e["uvlo_rise_typ"] - 9.859) > 0.25:
                        continue
                    if best is None or e["ovp_rise_max"] < best["ovp_rise_max"]:
                        best = e
        if best:
            best = dict(scale=k, **best)
            rows.append(best)
            say(f"  scale {k:4.2f}: {best['R102'] / 1e3:g}k/{best['R103'] / 1e3:g}k/{best['R104'] / 1e3:g}k -> OVP rise "
                f"{best['ovp_rise_min']:.3f}-{best['ovp_rise_max']:.3f} V, UVLO rise {best['uvlo_rise_min']:.3f}-"
                f"{best['uvlo_rise_max']:.3f} V, string {best['i_string_uA_at_25V']:.1f} uA at 25 V")
    # theoretical floor: zero leak, zero resistor tolerance
    say(f"  reference-only floor: minimum {target:.3f} V forces a maximum of {target * VOVPR[2] / VOVPR[0]:.3f} V "
        f"(V_OVPR max/min = {VOVPR[2] / VOVPR[0]:.4f}); with 0.1 % resistors "
        f"{target * VOVPR[2] / VOVPR[0] * (1 + RTOL) ** 2 / (1 - RTOL) ** 2:.3f} V (upper bound of the resistor term)")
    return rows


