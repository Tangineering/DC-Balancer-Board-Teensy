def node_coeffs(r1, r2, r3, iuv, iov):
    """V(N_UV) and V(N_OV) as a*VIN + b; iuv, iov flow out of the node into the pin (sim 5 sign convention)."""
    g1, g2, g3 = 1 / r1, 1 / r2, 1 / r3
    A = np.array([[g1 + g2, -g2], [-g2, g2 + g3]])
    s0 = np.linalg.solve(A, np.array([-iuv, -iov]))
    s1 = np.linalg.solve(A, np.array([g1 - iuv, -iov]))
    return (s1[0] - s0[0], s0[0]), (s1[1] - s0[1], s0[1])


def bands(r102, r103, r104, leak=True, rtol=RTOL):
    """Corner bands (min, max) of the four VCHG-IN thresholds, plus the typical no-leak values."""
    out = {k: [math.inf, -math.inf] for k in ("UVLO_rise", "UVLO_fall", "OVP_rise", "OVP_fall")}
    lk = (-1, 0, 1) if leak else (0,)
    corner = {}
    for s1, s2, s3, lu, lo in itertools.product((-1, 1), (-1, 1), (-1, 1), lk, lk):
        (au, bu), (ao, bo) = node_coeffs(r102 * (1 + s1 * rtol), r103 * (1 + s2 * rtol), r104 * (1 + s3 * rtol),
                                         lu * I_LEAK, lo * I_LEAK)
        for key, a, b, refs in (("UVLO_rise", au, bu, VUVLOR), ("UVLO_fall", au, bu, VUVLOF),
                                ("OVP_rise", ao, bo, VOVPR), ("OVP_fall", ao, bo, VOVPF)):
            for j, ref in ((0, refs[0]), (2, refs[2])):
                v = (ref - b) / a
                if v < out[key][0]:
                    out[key][0] = v
                    corner[(key, "min")] = (s1, s2, s3, lu, lo, j)
                if v > out[key][1]:
                    out[key][1] = v
                    corner[(key, "max")] = (s1, s2, s3, lu, lo, j)
    (au, bu), (ao, bo) = node_coeffs(r102, r103, r104, 0.0, 0.0)
    typ = dict(UVLO_rise=(VUVLOR[1] - bu) / au, UVLO_fall=(VUVLOF[1] - bu) / au,
               OVP_rise=(VOVPR[1] - bo) / ao, OVP_fall=(VOVPF[1] - bo) / ao)
    return {k: tuple(v) for k, v in out.items()}, typ, corner


def corner_pair(r102, r103, r104, which):
    """(rise, fall) of the OVP at the corner that minimises (which='lo') or maximises (which='hi') the rising
    threshold, evaluated with the same resistor and leak signs; falling uses the matching reference extreme."""
    b, _, corner = bands(r102, r103, r104)
    s1, s2, s3, lu, lo, j = corner[("OVP_rise", "min" if which == "lo" else "max")]
    (_, _), (ao, bo) = node_coeffs(r102 * (1 + s1 * RTOL), r103 * (1 + s2 * RTOL), r104 * (1 + s3 * RTOL),
                                   lu * I_LEAK, lo * I_LEAK)
    rise = (VOVPR[j] - bo) / ao
    fall = (VOVPF[j] - bo) / ao
    return rise, fall


def eseries(n):
    vals = []
    for i in range(n):
        v = round(10 ** (i / n), 2)
        vals.append(v)
    if n == 192:
        vals = [9.20 if abs(v - 9.19) < 1e-9 else v for v in vals]
    return vals


def decade_values(series, lo, hi):
    out = []
    for dec in (1e3, 1e4, 1e5, 1e6):
        for v in series:
            x = v * dec
            if lo <= x <= hi:
                out.append(round(x, 6))
    return sorted(set(out))


